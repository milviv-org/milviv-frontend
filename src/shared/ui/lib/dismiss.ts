/**
 * Решает, принять ли запрос слоя (dialog, drawer) сменить состояние открытия.
 *
 * Зачем: пока идёт сохранение, слой нельзя закрыть Esc, кликом мимо или свайпом — иначе пользователь
 * не увидит результат и может повторить действие. Reka сообщает о любой попытке закрытия одним
 * событием `update:open`, поэтому блокировка — в одном месте, а не в обработчике каждого способа.
 * Открыть слой можно всегда; закрытие кодом (родитель сам ставит `open = false`) сюда не попадает.
 */
export function shouldApplyOpenChange(nextOpen: boolean, dismissible: boolean): boolean {
  return nextOpen || dismissible
}
